def validate_schema(value, schema, path='$'):
    if 'anyOf' in schema:
        for branch in schema['anyOf']:
            try:
                validate_schema(value, branch, path)
            except AssertionError:
                continue
            return
        raise AssertionError((path, 'anyOf failed'))
    if 'enum' in schema:
        assert value in schema['enum'], (path, 'enum', value, schema['enum'])
    kind = schema.get('type')
    if kind == 'object':
        assert isinstance(value, dict), (path, 'object')
        assert set(schema.get('required', [])) <= set(value), (path, 'required')
        properties = schema.get('properties', {})
        if not schema.get('additionalProperties', True):
            assert set(value) <= set(properties), (path, 'additionalProperties')
        for key, item in value.items():
            validate_schema(item, properties[key], path + '.' + key)
    elif kind == 'array':
        assert isinstance(value, list), (path, 'array')
        assert len(value) >= schema.get('minItems', 0), (path, 'minItems')
        assert len(value) <= schema.get('maxItems', float('inf')), (path, 'maxItems')
        if schema.get('uniqueItems'):
            assert len({json.dumps(x, sort_keys=True) for x in value}) == len(value), (path, 'uniqueItems')
        for index, item in enumerate(value):
            validate_schema(item, schema['items'], path + f'[{index}]')
    elif kind == 'string':
        assert isinstance(value, str), (path, 'string')
    elif kind == 'boolean':
        assert isinstance(value, bool), (path, 'boolean')

